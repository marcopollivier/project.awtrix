const UNKNOWN = ['###', '#.#', '#.#', '#.#', '###'];

// Like the clock (uppercase letters setting on), lowercase is shown uppercase.
// Accents are folded so "SÁB" still renders; the real device has no accents either.
export function normalize(text) {
  return text.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
}

export function glyph(ch) {
  return RAW[ch] || UNKNOWN;
}

export function textWidth(text) {
  let w = 0;
  for (const ch of normalize(text)) w += glyph(ch)[0].length + 1;
  return Math.max(0, w - 1);
}
